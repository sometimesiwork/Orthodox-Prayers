void AddSluzhbyTailPrayers(Section& s, const DayInfo& day) {
    // ---------- 6. «Утреня» ----------
    {
        std::vector<std::pair<unsigned char, std::wstring>> ps;
        ps.push_back(Rub(day.isSunday
                             ? L"Воскресная утреня (по чину всенощного бдения)."
                             : L"Утреня суточного круга."));
        ps.push_back(
            Txt(L"1. Начало утрени (на всенощной — возглас «Слава Святей…» и пение «Слава в вышних Богу…» трижды; "
                L"на вседневной — двупсалмие 19 и 20 псалмов) и чтение Шестопсалмия (псалмы 3, 37, 62, 87, 102, 142) "
                L"при погашенных свечах."));
        ps.push_back(
            Txt(L"2. Великая ектения, пение «Бог Госпо́дь, и яви́ся нам, благослове́н Гряды́й во и́мя Госпо́дне» "
                L"(в будни Великого поста — «Аллилу́иа» со стихами и троичными тропарями гласа) и тропари дня."));
        ps.push_back(
            Txt(std::wstring(L"3. Чтение рядовых кафизм Псалтири и седальнов. ") +
                kMatinsKathismataByDow[std::clamp(day.dow, 0, 6)]));

        if (day.polyeleos || day.isSunday) {
            ps.push_back(
                Txt(L"4. Полиелей: пение псалмов 134 и 135 («Хвали́те и́мя Госпо́дне…», «Испове́дайтеся Го́сподеви, "
                    L"я́ко Благ…»), величание празднику (в воскресенье — воскресные тропари «Благослове́н еси́, Го́споди, "
                    L"научи́ мя оправда́нием Твои́м» и ипакои), степенны антифоны гласа."));
        }
        if (day.isSunday && day.matinsGospel >= 1 && day.matinsGospel <= 11) {
            ps.push_back(Rub(kMatinsGospels[day.matinsGospel]));
            ps.push_back(
                Txt(L"После Евангелия — пение «Воскресе́ние Христо́во ви́девше, поклони́мся Свято́му Го́споду Иису́су…», "
                    L"псалом 50, целование Евангелия и молитва «Спаси́, Бо́же, лю́ди Твоя́…»."));
        } else {
            ps.push_back(Txt(L"4. Чтение псалма 50 («Поми́луй мя, Бо́же…»)."));
        }

        ps.push_back(
            Txt(L"5. Каноны утрени: канон Октоиха (в воскресенье — воскресный, крестовоскресный и Богородичен) "
                L"и каноны святых Минеи (или Постной / Цветной Триоди). По 3-й песни — седален, по 6-й песни — "
                L"кондак и икос дня, пред 9-й песнью — песнь Богородицы «Величит душа Моя Господа…» («Честне́йшую Херуви́м…»)."));
        ps.push_back(
            Txt(L"6. По 9-й песни — светилен (в воскресенье — ексапостиларий по номеру утреннего Евангелия), "
                L"хвалитные псалмы 148, 149, 150 («Вся́кое дыха́ние да хва́лит Го́спода…») и стихиры на хвалитех."));
        if (day.polyeleos || day.isSunday) {
            ps.push_back(
                Txt(L"7. Великое славословие (поётся при отверстых Царских вратах), тропарь воскресный "
                    L"(в нечётные гласы 1, 3, 5, 7 — «Днесь спасе́ние ми́ру бысть…», в чётные 2, 4, 6, 8 — "
                    L"«Воскре́с из гро́ба и у́зы расто́ргнул еси́ а́довы…»), ектении, отпуст и 1-й час."));
        } else {
            ps.push_back(
                Txt(L"7. Вседневное славословие (читается), просительная ектения, стихиры на стиховне, "
                    L"«Благо́ есть испове́датися Го́сподеви…», Трисвятое, тропарь, сугубая ектения, отпуст и 1-й час."));
        }
        AddPrayer(s, L"Последование Утрени", std::move(ps));
        s.prayers.back().group = L"СУТОЧНЫЙ БОГОСЛУЖЕБНЫЙ КРУГ";
    }

    // ---------- 7. «Часы и Изобразительны» ----------
    {
        std::vector<std::pair<unsigned char, std::wstring>> ps;
        if (day.inBrightWeek) {
            ps.push_back(Rub(L"Часы Святой Пасхи (вместо 1-го, 3-го, 6-го и 9-го часов)."));
            ps.push_back(
                Txt(L"Поются целиком: «Христос воскресе» (трижды), «Воскресение Христово видевше» (трижды), "
                    L"ипакои «Предварившия утро яже о Марии…», кондак «Аще и во гроб снизшел еси…», тропари "
                    L"«Во гробе плотски, во аде же с душею яко Бог…», «Яко Живоносец…», «Господи, помилуй» (40), "
                    L"«Честнейшую Херувим…» и отпуст."));
        } else if (day.inPassionWeek && day.dow == 5) {
            ps.push_back(Rub(L"Великие (Царские) часы Великой Пятницы."));
            ps.push_back(
                Txt(L"На каждом часе (1-м, 3-м, 6-м и 9-м) читаются особые пророческие псалмы, паремия, "
                    L"Апостол и страстное Евангелие, поются самогласны тропари Страстей Христовых."));
        } else if (day.inGreatLent) {
            ps.push_back(Rub(L"Великопостные часы с кафизмами и Изобразительными."));
            ps.push_back(
                Txt(L"На 1-м, 3-м, 6-м и 9-м часах читаются рядовые кафизмы, поются великопостные тропари часа "
                    L"с земными поклонами, на 6-м часе — тропарь пророчества и паремия пророка Исаии. "
                    L"После 9-го часа — чин Изобразительных («Блаже́нны…», «Помяни́ нас, Го́споди, егда́ прии́деши "
                    L"во Ца́рствии Твое́м», Символ веры, «Осла́би, оста́ви, прости́, Бо́же…»)."));
        } else {
            ps.push_back(Rub(L"Вседневные часы: 1-й, 3-й, 6-й и 9-й."));
            ps.push_back(
                Txt(L"1-й час присоединяется к окончанию утрени (псалмы 5, 89, 100); 3-й час (псалмы 16, 24, 50) "
                    L"и 6-й час (псалмы 53, 54, 90) читаются перед началом Божественной литургии; 9-й час "
                    L"(псалмы 83, 84, 85) — перед вечерней."));
        }
        AddPrayer(s, L"Часы и Изобразительны", std::move(ps));
        s.prayers.back().group = L"СУТОЧНЫЙ БОГОСЛУЖЕБНЫЙ КРУГ";
    }

    // ---------- 8. «Божественная Литургия» ----------
    {
        std::vector<std::pair<unsigned char, std::wstring>> ps;
        if (day.inPassionWeek) {
            if (day.dow == 5) {
                ps.push_back(
                    Rub(L"Великая Пятница — день крестной смерти Спасителя: Литургия не совершается."));
                ps.push_back(
                    Txt(L"Утром служатся Царские часы и Изобразительны; днём — вечерня с выносом "
                        L"Святой Плащаницы; вечером — утреня Великой Субботы с чином погребения."));
            } else if (day.dow == 4 || day.dow == 6) {
                ps.push_back(
                    Rub(L"Литургия святителя Василия Великого в соединении с вечерней."));
                ps.push_back(
                    Txt(day.dow == 4
                            ? L"Великий Четверг (воспоминание Тайной Вечери): вместо Херувимской песни, "
                              L"причастна и «Да исполнятся уста наша…» поётся «Ве́чери Твоея́ та́йныя днесь, "
                              L"Сы́не Бо́жий, прича́стника мя приими́…»."
                            : L"Великая Суббота: чтение 15 паремий, переоблачение храма в светлые ризы, "
                              L"вместо Трисвятого — «Ели́цы во Христа́ крести́стеся…», вместо Херувимской — "
                              L"«Да молчи́т вся́кая плоть челове́ча…»."));
            } else {
                ps.push_back(
                    Rub(L"Литургия Преждеосвященных Даров святителя Григория Двоеслова."));
                ps.push_back(
                    Txt(L"Совершается на вечерне с чтением паремий Бытия и Притч, пением «Да исправится молитва моя…» "
                        L"и великим входом со Святыми Дарами при пении «Ныне Силы Небесныя с нами невидимо служат…»."));
            }
        } else if (day.inGreatLent) {
            if (day.dow == 3 || day.dow == 5) {
                ps.push_back(
                    Rub(L"Литургия Преждеосвященных Даров святителя Григория Двоеслова (среда и пятница Великого поста)."));
                ps.push_back(
                    Txt(L"Совершается в соединении с вечерней: кафизма 18-я («Ко Господу внегда скорбети ми…»), "
                        L"стихиры на «Господи, воззвах», вход, две паремии (Бытия и Притч), возжжение свечи "
                        L"«Свет Христов просвещает всех», пение «Да испра́вится моли́тва моя́, я́ко кади́ло пред Тобо́ю…», "
                        L"перенесение Преждеосвященных Даров под «Ны́не Си́лы Небе́сныя…», причащение верных."));
            } else {
                ps.push_back(
                    Rub(L"Полная Литургия в этот будний день Великого поста не положена (читаются Часы и Изобразительны)."));
            }
        } else {
            const bool basil =
                (day.isSunday && day.jdn >= day.lentStart && day.jdn < day.palmSun) ||
                (day.j.m == 1 && day.j.d == 1) || (day.j.m == 12 && day.j.d == 24) ||
                (day.j.m == 1 && day.j.d == 5);
            ps.push_back(
                Rub(basil ? L"Божественная литургия святителя Василия Великого."
                          : L"Божественная литургия святителя Иоанна Златоуста."));
            ps.push_back(
                Txt(L"1. Проскомидия (приготовление Святого Агнца и частиц на дискосе в алтаре во время чтения 3-го и 6-го часов)."));
            ps.push_back(
                Txt(L"2. Литургия оглашенных: возглас «Благослове́нно Ца́рство Отца́ и Сы́на и Свята́го Ду́ха…», "
                    L"великая ектения, 1-й антифон (псалом 102 «Благослови, душе моя, Господа»), 2-й антифон "
                    L"(псалом 145 «Хвали, душе моя, Господа» и «Единоро́дный Сы́не и Сло́ве Бо́жий…»), 3-й антифон "
                    L"(Заповеди блаженства «Во Ца́рствии Твое́м помяни́ нас, Го́споди…»)."));
            ps.push_back(
                Txt(L"3. Малый вход с Евангелием («Прииди́те, поклони́мся и припаде́м ко Христу́…»), тропари и кондаки дня, "
                    L"Трисвятое («Святы́й Бо́же, Святы́й Кре́пкий, Святы́й Безсме́ртный, поми́луй нас»), прокимен, "
                    L"чтение Апостола, Аллилуиарий, чтение Святого Евангелия, сугубая ектения и ектения об оглашенных."));
            ps.push_back(
                Txt(L"4. Литургия верных: Херувимская песнь («И́же Херуви́мы та́йно образу́юще…»), Великий вход "
                    L"с перенесением Честных Даров с жертвенника на престол, просительная ектения, Символ веры."));
            ps.push_back(
                Txt(L"5. Евхаристический канон (Анафора): «Ми́лость ми́ра, же́ртву хвалы́», «Свя́то, свя́то, свя́то Госпо́дь Савао́ф…», "
                    L"установительные слова Спасителя, «Твоя́ от Твои́х Тебе́ принося́ще о всех и за вся», преложение Святых Даров "
                    L"призыванием Святого Духа (эпиклеза), гимн Богородице («Досто́йно есть…» или «О Тебе́ ра́дуется…»)."));
            ps.push_back(
                Txt(L"6. Молитва Господня «О́тче наш…», возношение Святого Агнца («Свята́я святы́м»), причастный стих, "
                    L"молитва пред причащением («Ве́рую, Го́споди, и испове́дую…»), причащение духовенства и верных, "
                    L"«Ви́дехом Свет И́стинный…», «Да испо́лнятся уста́ на́ша…», заамвонная молитва, «Бу́ди и́мя Госпо́дне "
                    L"благослове́нно отны́не и до ве́ка» и отпуст."));
        }
        AddPrayer(s, L"Божественная Литургия", std::move(ps));
        s.prayers.back().group = L"СУТОЧНЫЙ БОГОСЛУЖЕБНЫЙ КРУГ";
    }

    // ---------- 9. «Псалтирь: уставное чтение кафизм» ----------
    {
        std::vector<std::pair<unsigned char, std::wstring>> ps;
        ps.push_back(Rub(L"Расписание чтения 20 кафизм Псалтири за седмицу (Типикон, гл. 17):"));
        ps.push_back(Rub(std::wstring(L"Сегодня (") + kWeekdayNames[day.dow] + L"): " +
                         kMatinsKathismataByDow[std::clamp(day.dow, 0, 6)]));
        ps.push_back(
            Txt(L"\u2022 Суббота на великой вечерне: 1-я кафизма («Блажен муж»)."));
        ps.push_back(
            Txt(L"\u2022 Воскресенье на утрене: 2-я и 3-я кафизмы (и 17-я в период пения полиелея)."));
        ps.push_back(
            Txt(L"\u2022 Понедельник: утреня — 4-я, 5-я (или 4, 5, 6); вечерня — 6-я."));
        ps.push_back(
            Txt(L"\u2022 Вторник: утреня — 7-я, 8-я (или 7, 8, 9); вечерня — 9-я."));
        ps.push_back(
            Txt(L"\u2022 Среда: утреня — 10-я, 11-я (или 10, 11, 12); вечерня — 12-я."));
        ps.push_back(
            Txt(L"\u2022 Четверг: утреня — 13-я, 14-я (или 13, 14, 15); вечерня — 15-я."));
        ps.push_back(
            Txt(L"\u2022 Пятница: утреня — 19-я, 20-я (или 16, 17); вечерня — 18-я."));
        ps.push_back(
            Txt(L"\u2022 Суббота: утреня — 16-я и 17-я («Непорочны»); вечерня — 1-я кафизма."));
        ps.push_back(
            Rub(L"В Великом посту вся Псалтирь прочитывается за седмицу дважды (покафизмно на утрене, часах и вечерне)."));
        AddPrayer(s, L"Устав чтения Псалтири (кафизм)", std::move(ps));
        s.prayers.back().group = L"СПРАВОЧНИК УСТАВА";
    }
}
