void AddBilingualHymnCard(Section& s, const wchar_t* group, const std::wstring& title,
                          const std::wstring& rubText, const std::wstring& csText,
                          const std::wstring& ruText) {
    Prayer p;
    p.group = group;
    p.title = title;
    if (!rubText.empty()) {
        PrayerPara r;
        r.text = rubText;
        r.lang = ParaLang::Both;
        r.style = kStyleRubric;
        p.paras.push_back(std::move(r));
    }
    if (!csText.empty()) {
        PrayerPara cs;
        cs.text = csText;
        cs.lang = ruText.empty() ? ParaLang::Both : ParaLang::Cs;
        cs.style = kStyleText;
        p.paras.push_back(std::move(cs));
    }
    if (!ruText.empty()) {
        PrayerPara ru;
        ru.text = ruText;
        ru.lang = ParaLang::Ru;
        ru.style = kStyleText;
        p.paras.push_back(std::move(ru));
    }
    s.prayers.push_back(std::move(p));
}

