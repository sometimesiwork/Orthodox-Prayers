int DayOfYear(const YMD& g) {
    static const int kDaysBeforeMonth[12] = {0,   31,  59,  90,  120, 151,
                                             181, 212, 243, 273, 304, 334};
    const int m = std::clamp(g.m, 1, 12);
    int doy = kDaysBeforeMonth[m - 1] + g.d;
    const bool leap = (g.y % 4 == 0 && (g.y % 100 != 0 || g.y % 400 == 0));
    if (leap && m > 2) ++doy;
    return std::clamp(doy, 1, 366);
}

